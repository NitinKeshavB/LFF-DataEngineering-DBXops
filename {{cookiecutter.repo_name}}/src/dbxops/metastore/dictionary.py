"""
Render the metadata database's data dictionary (tables, keys, columns, views) as markdown, from the model itself.

`context/03_Architecture/Metadata_Dictionary.md` is generated by `python -m dbxops.metastore dictionary`; a test
fails when it is out of date, so the documentation cannot drift from the code.
"""

from __future__ import annotations

from sqlalchemy import Table

from dbxops.metastore.model import (
    DERIVED_TABLES,
    ENTITIES,
    FACT_TABLES,
    RUNTIME_TABLES,
    WRITER_PLATFORM,
    MetaModel,
    build_model,
)
from dbxops.metastore.types import (
    JsonType,
    UtcTimestamp,
)

_OWNER = {WRITER_PLATFORM: "registry repo (`_platform`)"}


def _type_name(column) -> str:
    if isinstance(column.type, JsonType):
        return "JSON"
    if isinstance(column.type, UtcTimestamp):
        return "TIMESTAMP (UTC)"
    return str(column.type)


def _table_section(table: Table, heading: str) -> list[str]:
    key = [c.name for c in table.primary_key.columns]
    lines = [f"#### `{table.name}`", "", f"{heading} Primary key: `{', '.join(key)}`.", ""]
    lines += ["| column | type | null | key |", "|---|---|---|---|"]
    for column in table.columns:
        lines.append(
            f"| `{column.name}` | {_type_name(column)} | {'yes' if column.nullable else 'no'} | {'PK' if column.primary_key else ''} |"
        )
    return lines + [""]


def _groups(model: MetaModel) -> list[tuple[str, str, list[str]]]:
    """Return (title, description, table names) for each table pattern, in reading order."""
    parents = [spec.table for spec in ENTITIES.values()]
    children = [child.table for spec in ENTITIES.values() for child in spec.children]
    named = set(parents) | set(children) | set(DERIVED_TABLES) | set(FACT_TABLES)
    admin = [name for name in model.tables if name not in named]
    return [
        (
            "Pattern A: versioned definitions (parents)",
            "SCD2: a changed document closes the current row and inserts the next `record_version`.",
            parents,
        ),
        (
            "Pattern A: child tables",
            "A full snapshot of the children per parent version; no version columns of their own.",
            children,
        ),
        (
            "Pattern B: derived current state",
            "Replaced as a set per publisher; rows missing from the next publish become `is_active = false`.",
            list(DERIVED_TABLES),
        ),
        ("Pattern C: append-only facts", "Inserted once per idempotency key; never updated.", list(FACT_TABLES)),
        ("Administration", "Schema version bookkeeping.", admin),
    ]


def render_dictionary() -> str:
    """Return the data dictionary as markdown."""
    model = build_model()
    out = [
        "# Metadata database: data dictionary",
        "",
        "Generated from the model by `python -m dbxops.metastore dictionary` (`make metadata-dictionary`). Do not edit by hand:",
        "a test fails when this file differs from the model. Narrative and rules are in `Metadata_Model.md`.",
        "",
        f"Schema `{model.schema}`; {len(model.tables)} tables and {len(model.views())} views.",
        "",
    ]
    for title, description, names in _groups(model):
        out += [f"### {title}", "", description, ""]
        for name in names:
            heading = ""
            kind = next((k for k, spec in ENTITIES.items() if spec.table == name), None)
            if kind:
                heading = f"Owner: {_OWNER.get(ENTITIES[kind].owner, 'squad repo (its `project_id`)')}."
            elif name in RUNTIME_TABLES:
                heading = "Runtime fact, purged after `retention_days`."
            out += _table_section(model.tables[name], heading)
    out += [
        "### Views",
        "",
        "Read through these; they join each parent's current row to its children at the matching version.",
        "",
    ]
    out += [f"- `{name}`" for name in sorted(model.views())]
    return "\n".join(out) + "\n"
