"""
Turn the copied template into this squad's repository.

The template is copied verbatim (cookiecutter.json sets `_copy_without_render`), so it stays a working
repo that its own tests run against. This hook then:

1. checks the chosen domain against the taxonomy the project ships with;
2. removes the example bundles when asked;
3. replaces the example squad's identity with the answers, in every text file;
4. rewrites the four `metadata/_platform` snapshots and recomputes their hash headers;
5. runs `git init` and adds the pinned Lakeflow Framework as a submodule.

It uses only the standard library and PyYAML (a cookiecutter dependency), because it runs in
cookiecutter's environment, not the project's.
"""

import hashlib
import importlib.util
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

PROJECT_ID = re.sub(r"[\s_-]+", "_", "{{ cookiecutter.project_name }}".strip().lower()).strip("_")
REPO_NAME = "{{ cookiecutter.repo_name }}"
SQUAD_TITLE = "{{ cookiecutter.squad_title }}"
KIND = "{{ cookiecutter.kind }}"
DOMAIN = "{{ cookiecutter.domain }}"
EXAMPLES = "no" if KIND == "domain" else "{{ cookiecutter.include_examples }}"

EXAMPLE_DOMAIN = "claims"
SKIP_DIRS = {".git", "__pycache__", "lakeflow_framework"}
# the published platform library the registry repo installs; it is not this squad's distribution
REGISTRY_SCAFFOLD = Path("templates/registry-repo")
DIST_NAME = "cookie-cutter-dbx"
SNAPSHOT_HEADER = (
    "# machine-owned: generated by dbx-platform-registry; do not edit; change it through the registry. content-sha256="
)
SNAPSHOTS = ("repo.yaml", "teams.yaml", "domains.yaml", "glossary.ttl")
EXAMPLE_BUNDLES = ("dataops", "mlops", "aiops")
# tests that exercise the example bundles themselves; the rest of tests/bundles checks any bundle
EXAMPLE_TESTS = Path("tests/unit_tests/metastore/test_publish_real_repo.py")
KEPT_BUNDLE_TESTS = {"__init__.py", "test_bundles.py", "test_stage_framework.py"}
AT_LEAST_ONE_BUNDLE_TEST = re.compile(r"def test__there_is_at_least_one_bundle\(\):.*?\n\n\n", re.DOTALL)
KIND_LINE = re.compile(r"^kind: .*$", re.MULTILINE)
DOMAIN_LINE = re.compile(r"^(\s*domain:\s*)" + EXAMPLE_DOMAIN + r"\s*$", re.MULTILINE)


def identity_replacements() -> list[tuple[str, str]]:
    """Return the `(example value, answer)` pairs, longest first so a short token never splits a longer one."""
    bare = PROJECT_ID.replace("_", "")
    return [
        ("dbx-example-claims", "dbx-" + PROJECT_ID.replace("_", "-")),
        ("Example Claims Squad", SQUAD_TITLE),
        ("example_claims", PROJECT_ID),
        ("example-claims", PROJECT_ID.replace("_", "-")),
        ("EXAMPLECLAIMS", bare.upper()),
        ("exampleclaims", bare),
    ]


def text_files(root: Path) -> list[Path]:
    """Return every text file under `root`, skipping git data, caches and the framework checkout."""
    found = []
    for directory, subdirs, names in os.walk(root):
        subdirs[:] = [name for name in subdirs if name not in SKIP_DIRS]
        for name in names:
            path = Path(directory) / name
            if b"\0" not in path.read_bytes()[:4096]:
                found.append(path)
    return found


def with_header(body: str) -> str:
    """Return a snapshot body preceded by its hash header (the format `dbxops.registry.snapshots` checks)."""
    body = body.rstrip("\n") + "\n"
    return f"{SNAPSHOT_HEADER}{hashlib.sha256(body.encode('utf-8')).hexdigest()}\n{body}"


def check_domain(root: Path) -> None:
    """Exit with the taxonomy's own message (with suggestions) unless `DOMAIN` is a node of the taxonomy."""
    module_path = root / "src" / "dbxops" / "registry" / "domains.py"
    spec = importlib.util.spec_from_file_location("template_domains", module_path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module  # dataclasses look the module up by name
    spec.loader.exec_module(module)
    taxonomy = module.DomainTaxonomy.from_yaml(root / "metadata" / "_platform" / "domains.yaml")
    try:
        taxonomy.resolve(DOMAIN)
    except module.DomainError as error:
        sys.exit(f"ERROR: domain {DOMAIN!r} is not in the domain taxonomy. {error}")


def rewrite_text(root: Path) -> None:
    """Apply the identity replacements to every text file, except the registry scaffold's published-library name."""
    pairs = identity_replacements()
    for path in text_files(root):
        relative = path.relative_to(root)
        if relative.parts[:2] == ("metadata", "_platform"):
            continue
        original = path.read_text(encoding="utf-8")
        text = original
        for old, new in pairs:
            text = text.replace(old, new)
        if REGISTRY_SCAFFOLD not in relative.parents:
            text = text.replace(DIST_NAME, REPO_NAME)
        if relative == REGISTRY_SCAFFOLD / "projects" / "example_claims.yaml":
            text = DOMAIN_LINE.sub(lambda match: match.group(1) + DOMAIN, text)
            text = KIND_LINE.sub(f"kind: {KIND}", text)
        if text != original:
            path.write_text(text, encoding="utf-8")


def rewrite_snapshots(root: Path) -> None:
    """Rewrite the `_platform` snapshots for this squad and recompute each hash header."""
    pairs = identity_replacements()
    for name in SNAPSHOTS:
        path = root / "metadata" / "_platform" / name
        text = path.read_text(encoding="utf-8")
        body = text.partition("\n")[2] if text.startswith(SNAPSHOT_HEADER) else text
        for old, new in pairs:
            body = body.replace(old, new)
        if name in ("repo.yaml", "teams.yaml"):
            body = DOMAIN_LINE.sub(lambda match: match.group(1) + DOMAIN, body)
        if name == "repo.yaml":
            body = KIND_LINE.sub(f"kind: {KIND}", body)
        path.write_text(with_header(body), encoding="utf-8")


def rename_example_paths(root: Path) -> None:
    """Rename files whose name carries the example project id (the registry scaffold's example registration)."""
    for path in sorted(root.rglob("*example_claims*"), key=lambda found: len(found.parts), reverse=True):
        if not SKIP_DIRS.intersection(path.parts):
            path.rename(path.with_name(path.name.replace("example_claims", PROJECT_ID)))


def remove_examples(root: Path) -> None:
    """Delete the example bundles and the tests that exist only for them; keep the checks any bundle needs."""
    for name in EXAMPLE_BUNDLES:
        shutil.rmtree(root / "bundles" / name)
    (root / "bundles" / ".gitkeep").touch()
    (root / EXAMPLE_TESTS).unlink()
    bundle_tests = root / "tests" / "bundles"
    for path in bundle_tests.iterdir():
        if path.is_file() and path.name not in KEPT_BUNDLE_TESTS:
            path.unlink()
    guard = bundle_tests / "test_bundles.py"
    guard.write_text(AT_LEAST_ONE_BUNDLE_TEST.sub("", guard.read_text(encoding="utf-8"), count=1), encoding="utf-8")


def init_git(root: Path) -> None:
    """Create the git repository and add the framework submodule; report, never hide, a failure."""
    subprocess.run(["git", "init", "--quiet"], cwd=root, check=True)
    subprocess.run(["git", "symbolic-ref", "HEAD", "refs/heads/main"], cwd=root, check=True)
    added = subprocess.run(["bash", "scripts/add_framework.sh"], cwd=root, check=False)
    if added.returncode:
        print(
            "\nWARNING: the Lakeflow Framework submodule was not added (see the error above).\n"
            "Fix the cause (network? git?) and run: bash scripts/add_framework.sh\n",
            file=sys.stderr,
        )


def main() -> int:
    """Customise the generated project in place."""
    root = Path.cwd()
    check_domain(root)
    if KIND == "domain" and "{{ cookiecutter.include_examples }}" == "yes":
        print("NOTE: a domain repository holds only its own domain, so the example bundles were not included.")
    if EXAMPLES == "no":
        remove_examples(root)
    rewrite_text(root)
    rewrite_snapshots(root)
    rename_example_paths(root)
    init_git(root)
    print(f"\nCreated {REPO_NAME}. Next steps are in README.md ('Start building').")
    return 0


if __name__ == "__main__":
    sys.exit(main())
